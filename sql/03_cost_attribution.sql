USE DATABASE PURE_INSIGHTS_CASE_STUDY;
USE SCHEMA MONITORING;
ALTER SESSION SET TIMEZONE = 'UTC';

-- One canonical record per query. Latest ingestion timestamp, then stable value tie-break.
CREATE OR REPLACE VIEW V_QUERY_HISTORY_DEDUP AS
SELECT QUERY_ID, QUERY_TAG
FROM MOCK_QUERY_HISTORY
QUALIFY ROW_NUMBER() OVER (PARTITION BY QUERY_ID ORDER BY INGESTED_AT DESC, QUERY_TAG DESC) = 1;

CREATE OR REPLACE VIEW V_QUERY_ATTRIBUTION_DEDUP AS
SELECT QUERY_ID, WAREHOUSE_NAME, START_TIME, CREDITS_ATTRIBUTED_COMPUTE
FROM MOCK_QUERY_ATTRIBUTION_HISTORY
QUALIFY ROW_NUMBER() OVER (PARTITION BY QUERY_ID ORDER BY INGESTED_AT DESC, CREDITS_ATTRIBUTED_COMPUTE DESC) = 1;

CREATE OR REPLACE VIEW V_QUERY_CREDIT_QUARANTINE AS
SELECT * FROM V_QUERY_ATTRIBUTION_DEDUP
WHERE CREDITS_ATTRIBUTED_COMPUTE IS NULL OR CREDITS_ATTRIBUTED_COMPUTE < 0;

-- Keep unknown/malformed/missing tags visible in an explicit unallocated bucket.
CREATE OR REPLACE VIEW V_ATTRIBUTED_QUERIES AS
WITH TAGGED AS (
  SELECT A.*, TRY_PARSE_JSON(H.QUERY_TAG):report_id::VARCHAR AS TAG_REPORT_ID
  FROM V_QUERY_ATTRIBUTION_DEDUP A
  LEFT JOIN V_QUERY_HISTORY_DEDUP H ON A.QUERY_ID = H.QUERY_ID
  WHERE A.CREDITS_ATTRIBUTED_COMPUTE >= 0
), KNOWN_REPORTS AS (SELECT DISTINCT REPORT_ID FROM REPORT_METRICS)
SELECT T.QUERY_ID, T.WAREHOUSE_NAME, T.START_TIME,
       COALESCE(R.REPORT_ID, '__UNALLOCATED__') AS REPORT_ID,
       T.CREDITS_ATTRIBUTED_COMPUTE
FROM TAGGED T LEFT JOIN KNOWN_REPORTS R ON T.TAG_REPORT_ID = R.REPORT_ID;

CREATE OR REPLACE VIEW V_REPORT_CREDITS AS
SELECT REPORT_ID, SUM(CREDITS_ATTRIBUTED_COMPUTE) AS DIRECT_COMPUTE_CREDITS,
       COUNT(*) AS ATTRIBUTED_QUERY_COUNT
FROM V_ATTRIBUTED_QUERIES GROUP BY REPORT_ID;

-- Match the entire fixture period; do NOT copy this without matching production view/cost windows.
-- Negative invalid queries tied to a report make its cost incomplete rather than appearing as zero.
CREATE OR REPLACE VIEW V_REPORT_COST_PER_VIEW AS
WITH INVALID AS (
  SELECT TRY_PARSE_JSON(H.QUERY_TAG):report_id::VARCHAR AS REPORT_ID, COUNT(*) AS INVALID_QUERY_COUNT
  FROM V_QUERY_CREDIT_QUARANTINE A LEFT JOIN V_QUERY_HISTORY_DEDUP H ON A.QUERY_ID = H.QUERY_ID
  GROUP BY 1
), BASE AS (
  SELECT M.*, C.DIRECT_COMPUTE_CREDITS, COALESCE(C.ATTRIBUTED_QUERY_COUNT,0) AS ATTRIBUTED_QUERY_COUNT,
         COALESCE(I.INVALID_QUERY_COUNT,0) AS INVALID_QUERY_COUNT
  FROM REPORT_METRICS M LEFT JOIN V_REPORT_CREDITS C ON M.REPORT_ID=C.REPORT_ID
  LEFT JOIN INVALID I ON M.REPORT_ID=I.REPORT_ID
)
SELECT *,
       IFF(INVALID_QUERY_COUNT=0, COALESCE(DIRECT_COMPUTE_CREDITS,0)*3.00, NULL) AS SNOWFLAKE_COST_USD,
       IFF(INVALID_QUERY_COUNT=0, COALESCE(DIRECT_COMPUTE_CREDITS,0)*3.00+AWS_HOSTING_COST_USD, NULL) AS TOTAL_COST_USD,
       IFF(INVALID_QUERY_COUNT=0,
         (COALESCE(DIRECT_COMPUTE_CREDITS,0)*3.00+AWS_HOSTING_COST_USD)/NULLIF(MONTHLY_ACTIVE_VIEWS,0),NULL) AS COST_PER_VIEW_USD
FROM BASE;
-- $3/credit is an explicit assessment assumption, not a quoted Snowflake price.

-- Reconcile on warehouse and UTC day. Remaining billed compute is NOT automatically charged to reports.
-- It may include idle usage, unattributable short queries and data-window differences.
CREATE OR REPLACE VIEW V_WAREHOUSE_RECONCILIATION AS
WITH METERED AS (
  SELECT WAREHOUSE_NAME, TO_DATE(START_TIME) AS USAGE_DATE,
         SUM(CREDITS_USED_COMPUTE) AS BILLED_COMPUTE_CREDITS
  FROM MOCK_WAREHOUSE_METERING_HISTORY GROUP BY 1,2
), ATTRIBUTED AS (
  SELECT WAREHOUSE_NAME, TO_DATE(START_TIME) AS USAGE_DATE,
         SUM(IFF(REPORT_ID<>'__UNALLOCATED__',CREDITS_ATTRIBUTED_COMPUTE,0)) AS REPORT_CREDITS,
         SUM(IFF(REPORT_ID='__UNALLOCATED__',CREDITS_ATTRIBUTED_COMPUTE,0)) AS UNALLOCATED_QUERY_CREDITS
  FROM V_ATTRIBUTED_QUERIES GROUP BY 1,2
)
SELECT COALESCE(M.WAREHOUSE_NAME,A.WAREHOUSE_NAME) AS WAREHOUSE_NAME,
       COALESCE(M.USAGE_DATE,A.USAGE_DATE) AS USAGE_DATE,
       COALESCE(M.BILLED_COMPUTE_CREDITS,0) AS BILLED_COMPUTE_CREDITS,
       COALESCE(A.REPORT_CREDITS,0) AS REPORT_CREDITS,
       COALESCE(A.UNALLOCATED_QUERY_CREDITS,0) AS UNALLOCATED_QUERY_CREDITS,
       COALESCE(M.BILLED_COMPUTE_CREDITS,0)-COALESCE(A.REPORT_CREDITS,0)-COALESCE(A.UNALLOCATED_QUERY_CREDITS,0) AS UNATTRIBUTED_BILLED_CREDITS,
       IFF(COALESCE(M.BILLED_COMPUTE_CREDITS,0)<COALESCE(A.REPORT_CREDITS,0)+COALESCE(A.UNALLOCATED_QUERY_CREDITS,0),'OVER_ATTRIBUTED_REVIEW','RECONCILED') AS CHECK_STATUS
FROM METERED M FULL OUTER JOIN ATTRIBUTED A
 ON M.WAREHOUSE_NAME=A.WAREHOUSE_NAME AND M.USAGE_DATE=A.USAGE_DATE;

SELECT * FROM V_REPORT_COST_PER_VIEW ORDER BY TOTAL_COST_USD DESC NULLS LAST;
SELECT * FROM V_WAREHOUSE_RECONCILIATION;
SELECT * FROM V_QUERY_CREDIT_QUARANTINE;
